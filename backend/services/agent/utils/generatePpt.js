const addHeader = (slide, title) => {
  slide.addText(title || "", {
    x: 0.7,
    y: 0.4,
    w: 11.8,
    h: 0.55,
    fontSize: 25,
    bold: true,
    color: COLORS.secondary,
    fit: "shrink",
  });

  slide.addShape(pptxShape(slide, "line"), {
    x: 0.7,
    y: 1.05,
    w: 11.9,
    h: 0,
    line: {
      color: COLORS.border,
      width: 1,
    },
  });
};


