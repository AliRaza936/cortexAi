const addBullets = (ppt, data, page, total) => {
  const slide = ppt.addSlide();

  slide.background = {
    color: COLORS.light,
  };

  slide.addShape(ppt.ShapeType.rect, {
    x: 0,
    y: 0,
    w: 0.16,
    h: 7.5,
    fill: {
      color: COLORS.primary,
    },
    line: {
      color: COLORS.primary,
    },
  });

  addHeader(slide, data.title);

  const points = data?.points || [];

  points.slice(0, 6).forEach((point, index) => {
    const y = 1.45 + index * 0.8;

    slide.addShape(ppt.ShapeType.roundRect, {
      x: 0.75,
      y,
      w: 11.8,
      h: 0.6,

      fill: {
        color: index % 2
          ? COLORS.white
          : COLORS.blueLight,
      },

      line: {
        color: COLORS.border,
      },
    });

    slide.addShape(ppt.ShapeType.ellipse, {
      x: 1,
      y: y + 0.2,
      w: 0.14,
      h: 0.14,

      fill: {
        color: COLORS.primary,
      },

      line: {
        color: COLORS.primary,
      },
    });

    slide.addText(String(point), {
      x: 1.35,
      y: y + 0.1,
      w: 10.8,
      h: 0.4,

      fontSize: 14,
      color: COLORS.text,
      fit: "shrink",
    });
  });

  addFooter(slide, page, total);
};


