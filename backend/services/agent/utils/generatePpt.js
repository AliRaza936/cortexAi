import pptxgen from "pptxgenjs";

const COLORS = {
  primary: "2563EB",
  secondary: "0F172A",
  text: "334155",
  light: "F8FAFC",
  border: "E2E8F0",
  white: "FFFFFF",
  muted: "64748B",
  blueLight: "EFF6FF",
  blueMid: "DBEAFE",
  green: "10B981",
  red: "EF4444",
};


// ======================================================
// MAIN
// ======================================================

export const generatePpt = async (data) => {
  const ppt = new pptxgen();

  ppt.layout = "LAYOUT_WIDE";
  ppt.author = "CortexAI";
  ppt.company = "CortexAI";
  ppt.subject = data?.title || "Presentation";
  ppt.title = data?.title || "CortexAI Presentation";
  ppt.lang = "en-US";

  ppt.theme = {
    headFontFace: "Aptos Display",
    bodyFontFace: "Aptos",
    lang: "en-US",
  };

  // Cover
  addCover(ppt, data);

  // Content
  data?.slides?.forEach((slideData, index) => {
    addSlideByType(
      ppt,
      slideData,
      index + 1,
      data.slides.length
    );
  });

  // Final slide
  addThankYou(ppt);

  return ppt;
};


// ======================================================
// SLIDE TYPE ROUTER
// ======================================================

const addSlideByType = (ppt, data, page, total) => {
  switch (data?.type) {

    case "two_column":
      addTwoColumn(ppt, data, page, total);
      break;

    case "cards":
      addCards(ppt, data, page, total);
      break;

    case "comparison":
      addComparison(ppt, data, page, total);
      break;

    case "process":
      addProcess(ppt, data, page, total);
      break;

    case "stats":
      addStats(ppt, data, page, total);
      break;

    case "pros_cons":
      addProsCons(ppt, data, page, total);
      break;

    case "quote":
      addQuote(ppt, data, page, total);
      break;

    case "timeline":
      addTimeline(ppt, data, page, total);
      break;

    default:
      addBullets(ppt, data, page, total);
  }
};


