// ======================================================
// COMPARISON
// ======================================================

const addComparison = (ppt, data, page, total) => {
  const slide = ppt.addSlide();

  slide.background = {
    color: COLORS.light,
  };

  addHeader(slide, data.title);

  const headers = data?.headers || [];
  const rows = data?.rows || [];

  const x = 0.7;
  const y = 1.45;
  const width = 11.9;
  const columnWidth = width / headers.length;

  headers.forEach((header, index) => {
    slide.addShape(ppt.ShapeType.rect, {
      x: x + index * columnWidth,
      y,
      w: columnWidth,
      h: 0.65,

      fill: {
        color: COLORS.primary,
      },

      line: {
        color: COLORS.white,
      },
    });

    slide.addText(String(header), {
      x: x + index * columnWidth + 0.08,
      y: y + 0.15,
      w: columnWidth - 0.16,
      h: 0.3,

      fontSize: 11,
      bold: true,
      color: COLORS.white,
      align: "center",
      fit: "shrink",
    });
  });

  rows.slice(0, 7).forEach((row, rowIndex) => {
    row.forEach((cell, colIndex) => {
      const cellY =
        y + 0.65 + rowIndex * 0.62;

      slide.addShape(ppt.ShapeType.rect, {
        x: x + colIndex * columnWidth,
        y: cellY,
        w: columnWidth,
        h: 0.62,

        fill: {
          color: rowIndex % 2
            ? COLORS.white
            : "F1F5F9",
        },

        line: {
          color: COLORS.border,
        },
      });

      slide.addText(String(cell ?? ""), {
        x:
          x +
          colIndex * columnWidth +
          0.08,

        y: cellY + 0.12,

        w: columnWidth - 0.16,
        h: 0.35,

        fontSize: 10,
        color: COLORS.text,
        align: "center",
        fit: "shrink",
      });
    });
  });

  addFooter(slide, page, total);
};


