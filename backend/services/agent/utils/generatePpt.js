const addProcess = (ppt, data, page, total) => {
  const slide = ppt.addSlide();

  slide.background = {
    color: COLORS.light,
  };

  addHeader(slide, data.title);

  const steps = data?.steps?.slice(0, 6) || [];

  const gap = 11.5 / Math.max(steps.length, 1);

  steps.forEach((step, index) => {
    const x = 0.8 + index * gap;

    if (index < steps.length - 1) {
      slide.addShape(ppt.ShapeType.line, {
        x: x + 0.45,
        y: 3,
        w: gap - 0.45,
        h: 0,

        line: {
          color: COLORS.blueMid,
          width: 2,
        },
      });
    }

    slide.addShape(ppt.ShapeType.ellipse, {
      x,
      y: 2.65,
      w: 0.8,
      h: 0.8,

      fill: {
        color: COLORS.primary,
      },

      line: {
        color: COLORS.primary,
      },
    });

    slide.addText(String(index + 1), {
      x,
      y: 2.86,
      w: 0.8,
      h: 0.25,

      align: "center",
      fontSize: 14,
      bold: true,
      color: COLORS.white,
    });

    slide.addText(step?.title || "", {
      x: x - 0.35,
      y: 3.7,
      w: 1.5,
      h: 0.5,

      align: "center",
      fontSize: 13,
      bold: true,
      color: COLORS.secondary,
      fit: "shrink",
    });

    slide.addText(step?.description || "", {
      x: x - 0.55,
      y: 4.3,
      w: 1.9,
      h: 1,

      align: "center",
      fontSize: 10,
      color: COLORS.text,
      fit: "shrink",
    });
  });

  addFooter(slide, page, total);
};


